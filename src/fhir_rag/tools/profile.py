"""Profile the cohort: resource counts and sizes, note lengths, common codes.

`make profile` writes the result to docs/data.md. The numbers decide which
resource types get indexed (PLAN.md D3) and how notes get split (D4).
"""

import json
import sys
from collections import Counter
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from statistics import median_low

from fhir_rag.fhir.loader import (
    Bundle,
    iter_resources,
    load_bundle,
    patient_bundle_paths,
)
from fhir_rag.fhir.notes import note_text

__all__ = [
    "CODE_FIELDS",
    "CodeCount",
    "CohortProfile",
    "TypeStats",
    "build_profile",
    "main",
    "note_text",
    "render_markdown",
    "top_codes",
    "type_stats",
]

# Where each resource type keeps the code worth ranking.
CODE_FIELDS: Mapping[str, str] = {
    "Condition": "code",
    "Observation": "code",
    "MedicationRequest": "medicationCodeableConcept",
    "Procedure": "code",
    "Immunization": "vaccineCode",
}


@dataclass(frozen=True)
class TypeStats:
    resource_type: str
    count: int
    json_bytes: int  # UTF-8 length of json.dumps(resource, separators=(",", ":"))


@dataclass(frozen=True)
class CodeCount:
    system: str
    code: str
    display: str
    count: int


@dataclass(frozen=True)
class CohortProfile:
    patients: int
    resources_per_patient: list[int]
    types: list[TypeStats]
    note_words: list[int]
    # Keyed by resource type, in CODE_FIELDS order.
    top_codes: dict[str, list[CodeCount]]


def type_stats(bundles: Iterable[Bundle]) -> list[TypeStats]:
    """Count and compact-JSON size of each resource type across all bundles.

    Sorted by json_bytes, largest first; ties go to the alphabetically first type.
    """
    counts: Counter[str] = Counter()
    sizes: Counter[str] = Counter()
    for bundle in bundles:
        for resource in iter_resources(bundle):
            rtype = resource["resourceType"]
            counts[rtype] += 1
            sizes[rtype] += len(json.dumps(resource, separators=(",", ":")).encode())
    stats = [TypeStats(t, counts[t], sizes[t]) for t in counts]
    return sorted(stats, key=lambda s: (-s.json_bytes, s.resource_type))


def top_codes(bundles: Iterable[Bundle], resource_type: str, field: str, n: int) -> list[CodeCount]:
    """The n most common codes in `field` across resources of resource_type.

    Uses the first coding of the CodeableConcept, and the display text from the
    first resource seen with that code. Resources without the field are skipped.
    Sorted by count, highest first; ties go to the lower code string.
    """
    counts: Counter[tuple[str, str]] = Counter()
    displays: dict[tuple[str, str], str] = {}
    for bundle in bundles:
        for resource in iter_resources(bundle):
            if resource["resourceType"] != resource_type or field not in resource:
                continue
            coding = resource[field]["coding"][0]
            key = (coding["system"], coding["code"])
            counts[key] += 1
            displays.setdefault(key, coding.get("display", ""))
    ranked = sorted(counts.items(), key=lambda item: (-item[1], item[0][1]))
    return [CodeCount(s, c, displays[(s, c)], k) for (s, c), k in ranked[:n]]


def build_profile(bundles: Sequence[Bundle], top_n: int = 10) -> CohortProfile:
    """Combine the functions above into one profile. One bundle is one patient."""
    return CohortProfile(
        patients=len(bundles),
        resources_per_patient=[sum(1 for _ in iter_resources(b)) for b in bundles],
        types=type_stats(bundles),
        note_words=[
            len(note_text(r).split())
            for b in bundles
            for r in iter_resources(b)
            if r["resourceType"] == "DocumentReference"
        ],
        top_codes={t: top_codes(bundles, t, f, top_n) for t, f in CODE_FIELDS.items()},
    )


def _summary(values: list[int]) -> str:
    return f"min {min(values)}, median {median_low(values)}, max {max(values)}"


def render_markdown(profile: CohortProfile) -> str:
    """Render the profile as markdown; tests/test_profile.py pins the format.

    Medians use statistics.median_low, so they are always values from the data.
    """
    total = sum(s.json_bytes for s in profile.types) or 1
    lines = [
        "# Cohort profile",
        "",
        "Generated by `make profile` from `data/cohort/`. Sizes are compact JSON.",
        "",
        f"Patients: {profile.patients}",
        "",
        f"Resources per patient: {_summary(profile.resources_per_patient)}",
        "",
        "| Type | Count | Bytes | Share |",
        "|---|---:|---:|---:|",
    ]
    lines += [
        f"| {s.resource_type} | {s.count} | {s.json_bytes:,} | {100 * s.json_bytes / total:.1f}% |"
        for s in profile.types
    ]
    if profile.note_words:
        lines += ["", f"Note length (words): {_summary(profile.note_words)}"]
    lines += ["", "## Most common codes"]
    for rtype, codes in profile.top_codes.items():
        lines += [
            "",
            f"### {rtype}",
            "",
            "| Code | Display | Count |",
            "|---|---|---:|",
        ]
        lines += [f"| {c.code} | {c.display} | {c.count} |" for c in codes]
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    """`python -m fhir_rag.tools.profile COHORT_DIR` prints the markdown to stdout.

    Prints a usage line to stderr and returns 2 when COHORT_DIR is missing.
    """
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) != 1:
        print("usage: python -m fhir_rag.tools.profile COHORT_DIR", file=sys.stderr)
        return 2
    bundles = [load_bundle(p) for p in patient_bundle_paths(Path(args[0]))]
    sys.stdout.write(render_markdown(build_profile(bundles)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
