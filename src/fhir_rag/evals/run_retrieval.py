"""Retrieval eval: no API key, deterministic, runs on every pull request (D16).

    python -m fhir_rag.evals.run_retrieval [--split dev] [--check] [--update-baseline]

Compares retrieval configurations on the labeled questions and writes
evals/reports/retrieval-<split>.md. With --check, compares the default
configuration against evals/baselines/retrieval-<split>.json and exits 1 on
any cross-patient leak or on a drop of more than one question in a headline
metric (floating-point noise across machines can flip a near tie).

Metric conventions:
- hit/recall@k use the whole context the model would see: the pinned summary
  (when on) plus the first k ranked cards. Summary cards don't count against k.
- MRR uses the ranked cards only; the summary isn't ranked, so its order says
  nothing about retrieval quality.
"""

import argparse
import json
import sys
from collections.abc import Sequence
from dataclasses import dataclass, replace
from pathlib import Path

from fhir_rag.config import get_settings
from fhir_rag.evals.common import git_version, table
from fhir_rag.evals.metrics import bootstrap_ci, hit_at_k, mrr_at_k, recall_at_k
from fhir_rag.evals.questions import CATEGORIES, Question, Split, load_questions
from fhir_rag.retrieval.dense import Embedder
from fhir_rag.retrieval.retriever import RetrievalConfig, Retriever
from fhir_rag.store import Store

QUESTIONS = Path("evals/questions/questions.jsonl")
REPORTS = Path("evals/reports")
BASELINES = Path("evals/baselines")
HEADLINE = ("hit@10", "recall@10", "mrr@10")
DEFAULT = "hybrid + series + summary (default)"
MAX_K = 40


@dataclass(frozen=True)
class QuestionResult:
    question: Question
    summary: list[str]  # pinned summary cards; they don't count against k
    ranked: list[str]
    leaks: int

    def context(self, k: int) -> list[str]:
        return self.summary + self.ranked[:k]

    def hit(self, k: int) -> float:
        ctx = self.context(k)
        return hit_at_k(ctx, self.question.gold_groups, len(ctx))

    def recall(self, k: int) -> float:
        ctx = self.context(k)
        return recall_at_k(ctx, self.question.gold_groups, len(ctx))

    def mrr(self, k: int) -> float:
        return mrr_at_k(self.ranked, self.question.gold_groups, k)

    def metrics(self, k: int = 10) -> dict[str, float]:
        return {
            f"hit@{k}": self.hit(k),
            f"recall@{k}": self.recall(k),
            f"mrr@{k}": self.mrr(k),
        }


@dataclass(frozen=True)
class Variant:
    name: str
    config: RetrievalConfig
    report_k: int = 10  # cutoff used in the comparison table


def variants(default: RetrievalConfig, summary_size: int) -> list[Variant]:
    base = replace(default, k=MAX_K)
    plain = replace(base, series_expansion=0, pin_summary=False)
    no_summary = replace(base, pin_summary=False)
    return [
        Variant("bm25", replace(plain, mode="bm25")),
        Variant("dense", replace(plain, mode="dense")),
        Variant("hybrid", plain),
        Variant("hybrid + series", no_summary),
        Variant(
            f"hybrid + series, same budget (k={10 + summary_size})",
            no_summary,
            report_k=10 + summary_size,
        ),
        Variant("hybrid + summary", replace(base, series_expansion=0)),
        Variant(DEFAULT, base),
    ]


def evaluate(
    retriever: Retriever,
    store: Store,
    questions: Sequence[Question],
    config: RetrievalConfig,
) -> list[QuestionResult]:
    results = []
    for q in questions:
        hits = retriever.retrieve(q.patient_id, q.question, config)
        summary = [h.chunk.chunk_id for h in hits if h.source == "summary"]
        ranked = [h.chunk.chunk_id for h in hits if h.source != "summary"]
        leaks = sum(1 for c in summary + ranked if store.chunk_owner(c) != q.patient_id)
        results.append(QuestionResult(q, summary, ranked, leaks))
    return results


def _answerable(results: Sequence[QuestionResult]) -> list[QuestionResult]:
    return [r for r in results if r.question.answerable]


def mean_metrics(results: Sequence[QuestionResult], k: int = 10) -> dict[str, float]:
    members = _answerable(results)
    if not members:
        return {}
    per = [r.metrics(k) for r in members]
    return {m: sum(p[m] for p in per) / len(per) for m in per[0]}


def render(
    split: str, by_variant: dict[Variant, list[QuestionResult]], meta: dict[str, str]
) -> str:
    default_variant = next(v for v in by_variant if v.name == DEFAULT)
    default = by_variant[default_variant]
    answerable = _answerable(default)
    clusters = [r.question.patient_id for r in answerable]
    lines = [
        f"# Retrieval eval ({split} split)",
        "",
        "Generated by `make eval-retrieval`. " + ", ".join(f"{k}: `{v}`" for k, v in meta.items()),
        "",
        f"{len(default)} questions, {len(answerable)} answerable. Metrics count gold "
        "*groups* (questions.py). hit and recall use everything the model would see "
        "(pinned summary, when on, plus the first k ranked cards); MRR uses the ranked "
        "cards only. Intervals are 95% cluster-bootstrap CIs over patients.",
        "",
        "## Configurations",
        "",
    ]
    rows = []
    for variant, results in by_variant.items():
        k = variant.report_k
        m = mean_metrics(results, k)
        context = sum(len(r.context(k)) for r in results) / len(results)
        rows.append(
            [
                variant.name,
                k,
                f"{context:.1f}",
                f"{m[f'hit@{k}']:.3f}",
                f"{m[f'recall@{k}']:.3f}",
                f"{m[f'mrr@{k}']:.3f}",
                sum(r.leaks for r in results),
            ]
        )
    lines += table(
        [
            "Configuration",
            "k",
            "Cards in context",
            "hit",
            "recall",
            "mrr",
            "Leaked cards",
        ],
        rows,
    )

    lines += ["", f"## {DEFAULT}: confidence intervals", ""]
    rows = []
    for name, kind, k in [
        ("hit@5", "hit", 5),
        ("hit@10", "hit", 10),
        ("recall@10", "recall", 10),
        ("recall@20", "recall", 20),
        ("mrr@10 (ranked part)", "mrr", 10),
    ]:
        values = [getattr(r, kind)(k) for r in answerable]
        rows.append([name, str(bootstrap_ci(values, clusters))])
    lines += table(["Metric", "Mean [95% CI]"], rows)

    lines += ["", "## By category", ""]
    header = ["Category", "n"]
    rows_by_cat: dict[str, list[object]] = {}
    for variant in by_variant:
        if variant.report_k != 10:
            continue
        header.append(f"{variant.name} recall@10")
        for cat in CATEGORIES:
            members = [r for r in _answerable(by_variant[variant]) if r.question.category == cat]
            if members:
                row = rows_by_cat.setdefault(cat, [cat, len(members)])
                row.append(f"{sum(r.recall(10) for r in members) / len(members):.3f}")
    lines += table(header, list(rows_by_cat.values()))

    misses = [r for r in answerable if r.recall(10) < 1.0]
    lines += ["", f"## {DEFAULT}: questions with recall@10 below 1 ({len(misses)})", ""]
    rows = [
        [r.question.id, r.question.category, f"{r.recall(10):.2f}", r.question.question]
        for r in sorted(misses, key=lambda r: (r.recall(10), r.question.id))
    ]
    lines += table(["Question", "Category", "recall@10", "Text"], rows)
    return "\n".join(lines) + "\n"


def baseline_payload(results: Sequence[QuestionResult]) -> dict[str, object]:
    m = mean_metrics(results)
    return {
        "headline": {name: round(m[name], 6) for name in HEADLINE},
        "answerable": len(_answerable(results)),
        "leaks": sum(r.leaks for r in results),
    }


def check_baseline(current: dict[str, object], baseline: dict[str, object]) -> list[str]:
    """Regressions worth failing CI for; [] when the change is within tolerance."""
    failures = []
    leaks = current["leaks"]
    if isinstance(leaks, int) and leaks > 0:
        failures.append(f"{leaks} retrieved cards belong to another patient")
    n = current["answerable"]
    tolerance = 1 / n if isinstance(n, int) and n else 0.0
    now = current["headline"]
    before = baseline["headline"]
    assert isinstance(now, dict) and isinstance(before, dict)
    for metric, old in before.items():
        new = now.get(metric, 0.0)
        if new < old - tolerance - 1e-9:
            failures.append(
                f"{metric} dropped from {old:.3f} to {new:.3f} (tolerance {tolerance:.3f})"
            )
    return failures


def main(argv: Sequence[str] | None = None, embedder: Embedder | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--split", choices=["dev", "test", "all"], default="dev")
    parser.add_argument("--check", action="store_true", help="fail on regression vs baseline")
    parser.add_argument("--update-baseline", action="store_true")
    args = parser.parse_args(argv)

    settings = get_settings()
    split: Split | None = None if args.split == "all" else args.split
    questions = load_questions(QUESTIONS, split)
    if embedder is None:
        from fhir_rag.retrieval.dense import FastEmbedEmbedder

        embedder = FastEmbedEmbedder(settings.embedding_model)
    store = Store(settings.db_path)
    retriever = Retriever(store, embedder)
    default = RetrievalConfig(
        mode=settings.retrieval_mode,
        k=settings.top_k,
        series_expansion=settings.series_expansion,
        pin_summary=settings.pin_summary,
    )
    sizes = [len(store.pinned(p.patient_id)) for p in store.patients()]
    summary_size = round(sum(sizes) / len(sizes)) if sizes else 0
    by_variant = {
        v: evaluate(retriever, store, questions, v.config) for v in variants(default, summary_size)
    }
    meta = {
        "commit": git_version(),
        "cohort": store.meta("cohort_hash") or "",
        "cards": f"v{store.meta('card_version')}",
        "embedding": settings.embedding_model,
    }
    REPORTS.mkdir(parents=True, exist_ok=True)
    report = REPORTS / f"retrieval-{args.split}.md"
    report.write_text(render(args.split, by_variant, meta))
    default_results = next(r for v, r in by_variant.items() if v.name == DEFAULT)
    current = baseline_payload(default_results)
    print(f"wrote {report}: " + ", ".join(f"{k} {v}" for k, v in current.items()))

    baseline_path = BASELINES / f"retrieval-{args.split}.json"
    if args.update_baseline:
        BASELINES.mkdir(parents=True, exist_ok=True)
        baseline_path.write_text(json.dumps(current, indent=2, sort_keys=True) + "\n")
        print(f"updated {baseline_path}")
    if args.check:
        failures = check_baseline(current, json.loads(baseline_path.read_text()))
        for failure in failures:
            print(f"REGRESSION: {failure}", file=sys.stderr)
        return 1 if failures else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
